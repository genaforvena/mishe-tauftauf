"""The cutover driver must not proceed on a partial verdict, and must not leave the
plant stopped after an ordinary abort.

Two review findings from 2026-11-17 are pinned here, both against the real script:

1. `verify()` captured the helper's stdout and grepped for `VERIFIED` anywhere in
   it. The helpers print tree by tree and exit 2 when a per-tree evidence file
   cannot be written, so a clean first tree plus an unwritten second one passed as
   a full verdict. The driver now requires the helper's exit status and its
   `verify done rc=0` summary line.
2. A nonzero delta or NOT-CLEAN at minute ~3 of the window called `die()`, and
   nothing restarted the stopped units until the watchdog's sleep expired. The
   EXIT trap now rolls back a half-flip and restarts the recorded units in-process.

The watchdog side (a slow flip must not be mistaken for a dead one) is covered by
the last two tests: the body is generated by `--print-watchdog` and its liveness
constants are shortened, because the real sleep is 900 s and the real bound is 600 s.
"""
import os
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FLIP = REPO / "tools" / "root-migration-flip.sh"
TREES = ("mishe-tauftauf", ".omp", ".codex")

SYSTEMCTL = r"""#!/bin/bash
printf '%s\n' "$*" >>"$SANDBOX/systemctl.log"
# Record the calls made while quiesce holds the plant: the hold must be in place
# before the triggers are disarmed, not written afterwards.
[ -e "$SANDBOX/src/mishe-tauftauf/.mishe-tauftauf/hold" ] &&
    printf '%s\n' "$*" >>"$SANDBOX/hold-seen.log"
case "$*" in
  *" stop "*)
      # A trigger that refuses to stop: the flip must log it and keep draining.
      if [ -e "$SANDBOX/stop-fails" ] &&
         printf '%s' "$*" | grep -qE 'mishe-(wake-|next-due-|producer-dispatch|producer-delivery)'; then
          echo "Failed to stop unit: masked (fake)" >&2; exit 1
      fi ;;
  *"is-active"*)
      if [ -e "$SANDBOX/flip_active" ]; then echo active; exit 0; fi
      echo inactive; exit 3 ;;
  *"list-units"*"--type=path"*)
      printf 'fake-a.service loaded active running x\nfake-b.service loaded active running x\nfake-c.service loaded active running x\nfake-w.path loaded active waiting x\n'
      # A transient next-due timer: the stop removes it and the restart cannot
      # start that name again (observed 2026-11-17 11:28:18Z).
      [ -e "$SANDBOX/transient-timer" ] &&
          printf 'mishe-next-due-abc123.timer loaded active waiting x\n'
      # A transient review-retry timer, same shape (11:28:26Z).
      [ -e "$SANDBOX/review-retry-timer" ] &&
          printf 'mishe-release-review-retry-abc123-1794913066.timer loaded active waiting x\n' ;;
  *"list-units"*"--state=activating"*)
      # Wake units whose start job is queued behind the dispatch lock, one with
      # an omp already in its cgroup (live engine) and one without (queued).
      [ -e "$SANDBOX/queued-wakes" ] &&
          printf 'mishe-wake@queued.service loaded activating start start x\nmishe-wake@live.service loaded activating start start x\n' ;;
  *"list-units"*"--state=active"*)
      printf 'fake-a.service loaded active running x\nfake-b.service loaded active running x\nfake-c.service loaded active running x\n' ;;
  *"list-units"*) : ;;
  *" show "*"-p ControlGroup"*)
      # The test decides which unit's cgroup holds an omp process; the path is
      # $MIGRATION_CGROUP_ROOT/<unit>/cgroup.procs.
      u=
      for a in "$@"; do case "$a" in mishe-wake@*) u=$a ;; esac; done
      [ -n "$u" ] && printf '/%s\n' "$u"
      exit 0 ;;
  *" cat "*) echo "ExecStart=/bin/true $SANDBOX/src/mishe-tauftauf/x" ;;
  *" start "*)
      if printf '%s' "$*" | grep -qE ' start +mishe-next-due-'; then
          echo "Unit mishe-next-due-abc123.timer could not be found." >&2; exit 1
      fi
      # One-shot cut for the restart-order regression: terminate the flip in the
      # middle of restart_recorded, once, and let later starts through.
      if [ -n "${KILL_ON_START:-}" ] && [ ! -e "$SANDBOX/killed" ]; then
          n=$(grep -c ' start ' "$SANDBOX/systemctl.log")
          if [ "$n" -ge "$KILL_ON_START" ]; then
              : >"$SANDBOX/killed"
              kill -TERM "$PPID"
          fi
      fi ;;
esac
exit 0
"""

SYSTEMD_RUN = r"""#!/bin/bash
printf '%s\n' "$*" >>"$SANDBOX/systemd-run.log"
exit 0
"""


def sandbox(tmp_path):
    """A miniature plant: three source trees, three destination trees, a work dir,
    and a `systemctl` that records every call instead of touching real units."""
    root = tmp_path
    (root / "bin").mkdir()
    for name, body in (("systemctl", SYSTEMCTL), ("systemd-run", SYSTEMD_RUN)):
        path = root / "bin" / name
        path.write_text(body)
        path.chmod(0o755)
    for tree in TREES:
        (root / "src" / tree).mkdir(parents=True)
        (root / "src" / tree / "file.txt").write_text(f"hello {tree}\n")
        (root / "dst" / tree).mkdir(parents=True)
        shutil.copy2(root / "src" / tree / "file.txt", root / "dst" / tree / "file.txt")
    tools = root / "src" / "mishe-tauftauf" / "tools"
    tools.mkdir(parents=True)
    shutil.copy2(FLIP, tools / FLIP.name)        # preflight compares $0 with this copy
    (root / "work").mkdir()
    shutil.copy2(FLIP, root / "work" / "flip.sh")
    return root


def install_helper(root, helper_exit, helper_out):
    body = "#!/bin/bash\nprintf '%s\\n' '" + helper_out.replace("'", "'\\''") + "'\nexit " + str(helper_exit) + "\n"
    for path in (root / "work" / "verify-scoped.sh", root / "src" / "mishe-tauftauf" / "tools" / "root-migration-verify-scoped.sh"):
        path.write_text(body)
        path.chmod(0o755)


def env_for(root):
    return {**os.environ,
            "MIGRATION_SRC": str(root / "src"),
            "MIGRATION_DST": str(root / "dst"),
            "MIGRATION_WORK": str(root / "work"),
            "SANDBOX": str(root),
            "PATH": f"{root / 'bin'}:{os.environ['PATH']}"}


def flip(root, *args, extra_env=None):
    env = env_for(root)
    env.update(extra_env or {})
    return subprocess.run(["bash", str(root / "work" / "flip.sh"), *args],
                          env=env, capture_output=True, text=True, timeout=180)


def calls(root):
    path = root / "systemctl.log"
    return path.read_text().splitlines() if path.exists() else []


def test_partial_verdict_aborts_before_any_rename_and_restarts_units(tmp_path):
    """Regression: one verified tree plus exit 2 must not cut over."""
    root = sandbox(tmp_path)
    install_helper(root, 2, "  VERIFIED mishe-tauftauf\ncannot write evidence file for .omp")

    done = flip(root, "--execute")

    assert done.returncode == 1, done.stdout + done.stderr
    assert "exited 2 without a full verdict" in done.stdout + done.stderr
    for tree in TREES:
        assert (root / "src" / tree).is_dir()
        assert not (root / "src" / tree).is_symlink()
        assert not (root / "src" / f"{tree}.pre-migration").exists()
    assert not (root / "work" / "flip.done").exists()
    assert any("start fake-a.service" in line for line in calls(root)), calls(root)


def test_not_clean_aborts_and_restarts_units(tmp_path):
    root = sandbox(tmp_path)
    install_helper(root, 1, "  VERIFIED mishe-tauftauf\n  NOT-CLEAN .omp\n=== scoped verify done rc=1")

