def test_clean_run_flips_and_restarts_units(tmp_path):
    root = sandbox(tmp_path)
    install_helper(root, 0, "  VERIFIED mishe-tauftauf\n=== scoped verify done rc=0")

    done = flip(root, "--execute")

    assert done.returncode == 0, done.stdout + done.stderr
    for tree in TREES:
        assert (root / "src" / tree).is_symlink()
        assert os.path.realpath(root / "src" / tree) == str(root / "dst" / tree)
        assert (root / "src" / f"{tree}.pre-migration").is_dir()
    assert (root / "work" / "flip.done").exists()
    assert any("start fake-a.service" in line for line in calls(root)), calls(root)
    # Regression: the drain check's status was inverted, so every execute slept the
    # full 30 s and then warned about writers it had not found.
    assert "no writers left on the moved trees" in done.stdout + done.stderr
    assert "warning: writers still present" not in done.stdout + done.stderr
    # Regression: target_units asked for services and timers only, so the
    # mishe-wake-*.path triggers stayed armed and fired new wakes mid-delta.
    assert any("start fake-w.path" in line for line in calls(root)), calls(root)


def test_a_failed_trigger_stop_is_logged_and_the_flip_continues(tmp_path):
    """Regression (field-review review, chat #302375): quiesce stopped the wake and
    delivery triggers with `|| true`, so a trigger that refused to stop left no
    evidence in flip.log while it could still fire a wake or a promotion into the
    drain -- the 09:34 abort class. The stop stays non-fatal: the engine and delivery
    re-samples are the bounds that catch it."""
    root = sandbox(tmp_path)
    install_helper(root, 0, "  VERIFIED mishe-tauftauf\n=== scoped verify done rc=0")
    (root / "stop-fails").write_text("")

    done = flip(root, "--execute")

    out = done.stdout + done.stderr
    assert done.returncode == 0, out
    assert "wake trigger stop failed (continuing)" in out, out
    assert "delivery trigger stop failed (continuing)" in out, out
    for tree in TREES:
        assert (root / "src" / tree).is_symlink(), out
    assert (root / "work" / "flip.done").exists()
    # The per-unit stop loop already logged failures; it must not have been affected.
    assert any("start fake-a.service" in line for line in calls(root)), calls(root)


def detach_argv(root):
    path = root / "systemd-run.log"
    lines = path.read_text().splitlines() if path.exists() else []
    return lines[-1] if lines else ""


def test_detach_forwards_the_callers_engine_bound_and_wake_key(tmp_path):
    """Regression: systemd-run starts the flip in a clean environment, so the
    caller's MIGRATION_ENGINE_TIMEOUT, MIGRATION_DELIVERY_DRAIN_TIMEOUT and
    MISHE_WAKE_KEY were silently dropped -- a caller's short bound became the
    default, and target_units lost the exclusion that keeps the launching wake's
    unit out of the stop list."""
    root = sandbox(tmp_path)
    install_helper(root, 0, "  VERIFIED mishe-tauftauf\n=== scoped verify done rc=0")

    flip(root, "--execute", "--scoped", "--detach",
         extra_env={"MIGRATION_ENGINE_TIMEOUT": "45",
                    "MIGRATION_DELIVERY_DRAIN_TIMEOUT": "120",
                    "MISHE_WAKE_KEY": "wake-health1-1794"})

    argv = detach_argv(root)
    assert "--setenv=MIGRATION_ENGINE_TIMEOUT=45" in argv, argv
    assert "--setenv=MIGRATION_DELIVERY_DRAIN_TIMEOUT=120" in argv, argv
    assert "--setenv=MISHE_WAKE_KEY=wake-health1-1794" in argv, argv
    assert "--setenv=MIGRATION_SRC=" in argv, argv


def test_detach_passes_no_empty_setenv_when_the_caller_sets_neither(tmp_path):
    root = sandbox(tmp_path)
    install_helper(root, 0, "  VERIFIED mishe-tauftauf\n=== scoped verify done rc=0")
