def test_termination_during_restart_starts_every_listed_unit(tmp_path):
    """Regression: flip.done was written before restart_recorded, and both the EXIT
    trap and the watchdog return early on that marker. A cut inside the restart loop
    therefore left stopped units with nothing to restart them: on the pre-fix bytes
    this test saw 2 of 3 units started, rc 143 and no restore line. The marker is now
    written after the restart, so the trap reaches restore_plant, which recognises
    the consistent symlinks and only restarts."""
    root = sandbox(tmp_path)
    install_helper(root, 0, "  VERIFIED mishe-tauftauf\n=== scoped verify done rc=0")

    done = flip(root, "--execute", extra_env={"KILL_ON_START": "2"})

    assert done.returncode != 0, done.stdout + done.stderr
    starts = [line for line in calls(root) if " start " in line]
    for unit in ("fake-a.service", "fake-b.service", "fake-c.service"):
        assert any(f"start {unit}" in line for line in starts), (unit, calls(root))
    # The cut came after the rename: the restore must not roll a flipped tree back.
    for tree in TREES:
        assert (root / "src" / tree).is_symlink()
        assert (root / "src" / f"{tree}.pre-migration").is_dir()


def watchdog_body(root, *, bound, pid):
    printed = subprocess.run(["bash", str(root / "work" / "flip.sh"),
                              "--print-watchdog", "--watchdog-seconds", "0"],
                             env=env_for(root), capture_output=True, text=True, timeout=60)
    assert printed.returncode == 0, printed.stderr
    body = printed.stdout
    import re
    body = re.sub(r"^F=.*$", f"F={pid}", body, flags=re.M)
    return body.replace("-ge 60", f"-ge {bound}").replace("\nsleep 10\n", "\nsleep 1\n")


def watchdog_hold_token(body):
    """The token line the watchdog compares the hold against: the flip's own text."""
    line = next(l for l in body.splitlines() if l.startswith("T="))
    return line.split("=", 1)[1].strip("'")


def test_watchdog_rolls_back_when_the_flip_is_gone(tmp_path):
    root = sandbox(tmp_path)
    (root / "work" / "flip.units").write_text(
        "fake-a.service\nmishe-next-due-abc123.timer\n"
        "mishe-release-review-retry-abc123-1794913066.timer\n")
    (root / "src" / "mishe-tauftauf").rename(root / "src" / "mishe-tauftauf.pre-migration")
    shutil.rmtree(root / "src" / ".omp")
    (root / "src" / ".omp").symlink_to(root / "dst" / ".omp")
    body = watchdog_body(root, bound=60, pid=999999)

    run = subprocess.run(["bash", "-c", body], env=env_for(root),
                         capture_output=True, text=True, timeout=120)

    assert run.returncode == 0, run.stdout + run.stderr
    log = (root / "work" / "flip.log").read_text()
    assert "rollback mishe-tauftauf" in log, log
    assert "rollback .omp" not in log and ".omp is flipped and consistent" in log, log
