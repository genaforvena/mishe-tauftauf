"""A sibling plant's pinned fork must not be able to write or start our units."""
from pathlib import Path

import pytest

from mishe_tauftauf import cross_plant, units

PREFIX = "nginx2root"


def _sibling(tmp_path, *, prefix="nginx2root", marker=None, wake_prefix=None, timer_prefix=None,
             name="second-plant"):
    """A sibling plant whose pinned release is a fork of this runtime."""
    marker = marker or f"# {PREFIX}-generated: second plant runtime"
    wake_prefix = PREFIX if wake_prefix is None else wake_prefix
    timer_prefix = PREFIX if timer_prefix is None else timer_prefix
    site = tmp_path / name / ".mishe-tauftauf"
    release = tmp_path / name / "release"
    pkg = release / "src" / "mishe_tauftauf"
    pkg.mkdir(parents=True)
    (pkg / "units.py").write_text(f"MARKER = {marker!r}\n", encoding="utf-8")
    (pkg / "release_promotion.py").write_text(
        "args = argparse.Namespace(command='sync', prefix=" + repr(prefix) + ")\n", encoding="utf-8")
    (pkg / "wake.py").write_text(f'cmd = "systemctl --user start {wake_prefix}-wake@{{role}}.service"\n',
                                 encoding="utf-8")
    (pkg / "arm.py").write_text(f'TIMER_UNIT = "{timer_prefix}-next-due"\n', encoding="utf-8")
    (site / "runtime").mkdir(parents=True)
    (site / "runtime" / "current").symlink_to(release, target_is_directory=True)
    return site


def test_correctly_forked_sibling_release_is_silent(tmp_path):
    home = tmp_path / "main" / ".mishe-tauftauf"
    home.mkdir(parents=True)
    _sibling(tmp_path)
    assert cross_plant.release_problems(home, our_prefix="mishe", our_marker=units.MARKER) == []


def test_broken_sibling_fork_names_the_promotion_and_start_collisions(tmp_path):
    # The exact 03:54Z cause: own marker, but promotion and start names still ours.
    home = tmp_path / "main" / ".mishe-tauftauf"
    home.mkdir(parents=True)
    _sibling(tmp_path, prefix="mishe", wake_prefix="mishe", timer_prefix="mishe")
    problems = cross_plant.release_problems(home, our_prefix="mishe", our_marker=units.MARKER)
    assert any("promotes mishe-named units" in p and "second-plant" in p for p in problems)
    assert any("starts our mishe-* units" in p for p in problems)


def test_wake_prefix_gap_is_separate_from_the_promotion_prefix(tmp_path):
    # Fork change 4 is applied, change 3 is not: their wake still starts our units.
    home = tmp_path / "main" / ".mishe-tauftauf"
    home.mkdir(parents=True)
    _sibling(tmp_path, wake_prefix="mishe", timer_prefix="nginx2root")
    problems = cross_plant.release_problems(home, our_prefix="mishe", our_marker=units.MARKER)
    assert len(problems) == 1 and "starts our mishe-* units" in problems[0]


def test_unrelated_directory_and_undecidable_release_are_not_claimed(tmp_path):
    home = tmp_path / "main" / ".mishe-tauftauf"
    home.mkdir(parents=True)
    other = tmp_path / "other" / ".mishe-tauftauf" / "runtime"
    other.mkdir(parents=True)
    (other / "current").symlink_to(tmp_path / "other" / "release", target_is_directory=True)
    assert cross_plant.release_problems(home, our_prefix="mishe", our_marker=units.MARKER) == []


@pytest.fixture
def cfg(tmp_path):
    home = tmp_path / "main" / ".mishe-tauftauf"
    pin = tmp_path / "rel" / "src"
    (pin / "mishe_tauftauf").mkdir(parents=True)
    (pin / "mishe_tauftauf" / "__init__.py").write_text("", encoding="utf-8")
    (home / "bin").mkdir(parents=True)
    (home / "bin" / "mishe-tauftauf").write_text(
        f"#!/bin/sh\nexport PYTHONPATH={pin}\nexec python -m mishe_tauftauf \"$@\"\n", encoding="utf-8")
    return units.Config(home=home, repo=tmp_path / "repo", python="/usr/bin/python3",
                        pythonpath=str(pin), unit_dir=tmp_path / "units")


def test_doctor_red_on_a_sibling_fork_break_before_any_unit_is_touched(cfg, tmp_path):
    units.sync(cfg, ["genome"], runner=lambda c: None)
    assert units.doctor(cfg, ["genome"]).problems == []
    _sibling(tmp_path, prefix="mishe", wake_prefix="mishe", timer_prefix="mishe")
    report = units.doctor(cfg, ["genome"])
    assert report.state == "RED"
    assert any("promotes mishe-named units" in p for p in report.problems)
    assert not any("foreign-generated by" in p for p in report.problems)  # no collision yet


def test_fork_cause_survives_doctor_reason_on_a_mass_collision(cfg, tmp_path):
    """A broken fork is the cause; a mass collision is the effect. Both must fit the RED reason."""
    from mishe_tauftauf import runtime_cli

    units.sync(cfg, ["genome"], runner=lambda c: None)
    rendered = units.render(cfg, ["genome"])
    for rel, text in rendered.items():
        (cfg.unit_dir / rel).write_text(
            "# nginx2root-generated: second plant runtime\n" + text, encoding="utf-8")
    _sibling(tmp_path, prefix="mishe", wake_prefix="mishe", timer_prefix="mishe")

    report = units.doctor(cfg, ["genome"])
    assert report.state == "RED"
    reason = runtime_cli.doctor_reason(report)
    assert f"{len(rendered)} of our units are foreign-generated" in reason
    assert "promotes mishe-named units" in reason
